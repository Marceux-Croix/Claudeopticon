# The CommonMark reference for the todo grammar's differential test: random todo documents,
# each line's reading by commonmark.py (a port of commonmark.js, the spec's reference parser), written as
# tests/fixtures/commonmark-items.ts. Run from the mod folder:
#
#     uv run --no-project --with commonmark==0.9.1 python -I scripts/commonmark-fixture.py 1 400 > tests/fixtures/commonmark-items.ts
#
# The documents are random: 2 to 9 lines of list items, checkbox lines,
# paragraphs, fences, comments and headings, each behind one of ten indents (spaces and tabs).
import json, random, re, sys
import commonmark

seed, count = int(sys.argv[1]), int(sys.argv[2])
random.seed(seed)
INDENTS = ['', ' ', '  ', '   ', '    ', '      ', '        ', '\t', '  \t', '\t\t']
FRAGMENTS = ['- [ ] a', '- [x] b', '* [ ] c', '+ [~] d', '- [ ] e', '1. x', 'para text', '', '', '```', '~~~', '````', '<!--', '-->', '<!-- one -->', '## H', 'Label:', '- plain']
BOX = re.compile(r'^\[[ xX~>]\]\s')
parser = commonmark.Parser()
rows = []
for _ in range(count):
    lines = [random.choice(INDENTS) + random.choice(FRAGMENTS) for _ in range(random.randint(2, 9))]
    ast = parser.parse('\n'.join(lines))
    item = [False] * len(lines)
    kind = [''] * len(lines)
    for node, entering in ast.walker():
        if not entering or node.sourcepos is None:
            continue
        (start, _), (end, _) = node.sourcepos
        if node.t in ('code_block', 'html_block', 'paragraph', 'heading'):
            for k in range(start - 1, min(end, len(lines))):
                kind[k] = node.t
        if node.t == 'item' and node.list_data.get('type') == 'bullet':
            child = node.first_child
            if child is not None and child.t == 'paragraph' and child.sourcepos[0][0] == start:
                text, c = '', child.first_child
                while c is not None and c.t == 'text':
                    text += c.literal
                    c = c.nxt
                if BOX.match(text + ' '):
                    item[start - 1] = True
    rows.append({'lines': lines, 'items': item, 'kinds': kind})

print('// Generated by scripts/commonmark-fixture.py %d %d (commonmark.py 0.9.1). Do not edit by hand.' % (seed, count))
print('// Per document: its lines, which lines CommonMark reads as checkbox list items, and the leaf block of each line.')
print('export const COMMONMARK_ITEMS: { lines: string[]; items: boolean[]; kinds: string[] }[] = [')
for row in rows:
    print('  %s,' % json.dumps(row, ensure_ascii=True))
print(']')
