// The CommonMark reference for HTML blocks and block quotes in the todo grammar: random todo
// documents read by commonmark.js 0.31.2 (the spec's reference parser, spec 0.31.2), written as
// tests/fixtures/commonmark-html-quotes.ts. commonmark.py 0.9.1 (scripts/commonmark-fixture.py) predates
// spec 0.30, so it lacks `<textarea>` (type 1) and lets a lone tag (type 7) end a lazy paragraph. Run from
// the mod folder, with the path of an unpacked `npm pack commonmark@0.31.2` (nothing is installed):
//
//     node scripts/commonmark-html-fixture.cjs <package>/dist/commonmark.js 1 500 > tests/fixtures/commonmark-html-quotes.ts
//
// The documents: 2 to 9 lines of list-item, checkbox and prose fragments plus HTML blocks of all 7 types and block quotes,
// each behind one of ten indents, a quarter of them behind `> ` or a checkbox item. A list item inside a
// block quote counts as no item (the mod's stated design). A document where CommonMark reads a checkbox
// line as paragraph text is left out: there the mod's deliberate exception applies (an over-indented
// checkbox item under a paragraph line is an item); the count of those is in the header.
const cm = require(process.argv[2])
const seed0 = Number(process.argv[3])
const count = Number(process.argv[4])

// A small seeded generator (mulberry32), so the fixture is the same on every run.
let seed = seed0 >>> 0
const random = () => {
  seed = (seed + 0x6d2b79f5) >>> 0
  let t = seed
  t = Math.imul(t ^ (t >>> 15), t | 1)
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61)

  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const pick = list => list[Math.floor(random() * list.length)]

const INDENTS = ['', ' ', '  ', '   ', '    ', '      ', '        ', '\t', '  \t', '\t\t']
const FRAGMENTS = ['- [ ] a', '- [x] b', '* [ ] c', '+ [~] d', '- [ ] e', '1. x', 'para text', '', '', '```', '~~~', '````', '<!--', '-->', '<!-- one -->', '## H', 'Label:', '- plain']
const HTML = ['<div>', '</div>', '<details>', '</details>', '<summary>x</summary>', '<pre>', '</pre>', '<script>', '</script>', '<?php', '?>', '<!DOCTYPE html>', '<!X', '>', '<![CDATA[', ']]>', '<span>', '</span>', '<a href="x">', '<custom-tag a=1 b>', '<b>text</b>', 'x <div>', '<DIV class="y">', '<div/>', '<textarea>', '</textarea>', '<prefix>']
const QUOTES = ['> ', '>', '> - [ ] q', '>     - [ ] q', '> > - [ ] q', '> ```', '> <div>', '> para', ' > - [ ] q', '>\t- [ ] q']
const ALL = [...FRAGMENTS, ...HTML, ...QUOTES]
const BOX = /^\[[ xX~>]\]\s/
const CHECKBOX = /^\s*[-*+] \[([ xX~>])\]\s+/
const KINDS = new Set(['code_block', 'html_block', 'paragraph', 'heading'])

const parser = new cm.Parser()
const rows = []
let left = 0
while (rows.length < count) {
  const lines = Array.from({ length: 2 + Math.floor(random() * 8) }, () => {
    const prefix = random() < 0.25 ? pick(['', '> ', '- [ ] p ']) : ''

    return pick(INDENTS) + prefix + pick(ALL)
  })
  const items = lines.map(() => false)
  const kinds = lines.map(() => '')
  const walker = parser.parse(lines.join('\n')).walker()
  let ev
  while ((ev = walker.next())) {
    const node = ev.node
    if (!ev.entering || !node.sourcepos) {
      continue
    }
    const [[start], [end]] = node.sourcepos
    if (KINDS.has(node.type) || (node.type === 'block_quote' && kinds[start - 1] === '')) {
      for (let k = start - 1; k < Math.min(end, lines.length); k += 1) {
        kinds[k] = node.type
      }
    }
    if (node.type === 'item' && node.listType === 'bullet') {
      let up = node.parent
      let isInQuote = false
      while (up) {
        isInQuote ||= up.type === 'block_quote'
        up = up.parent
      }
      const child = node.firstChild
      if (!isInQuote && child && child.type === 'paragraph' && child.sourcepos[0][0] === start) {
        let text = ''
        for (let c = child.firstChild; c && c.type === 'text'; c = c.next) {
          text += c.literal
        }
        items[start - 1] = BOX.test(`${text} `)
      }
    }
  }
  if (lines.some((line, k) => kinds[k] === 'paragraph' && CHECKBOX.test(line) && !items[k])) {
    left += 1
    continue
  }
  rows.push({ lines, items, kinds })
}

console.log(`// Generated by scripts/commonmark-html-fixture.cjs (commonmark.js 0.31.2) ${seed0} ${count}; ${left} documents with the deliberate exception left out. Do not edit by hand.`)
console.log('// Per document: its lines, which lines CommonMark reads as checkbox list items (none in a block quote), and the block of each line.')
console.log('export const COMMONMARK_HTML_QUOTES: { lines: string[]; items: boolean[]; kinds: string[] }[] = [')
for (const row of rows) {
  console.log(`  ${JSON.stringify(row)},`)
}
console.log(']')
